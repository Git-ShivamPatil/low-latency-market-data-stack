#!/usr/bin/env python3
"""Generate the Rust codec and the C++ header from schema/market-data.xml.

    python3 schema/codegen.py            # write the generated files
    python3 schema/codegen.py --check    # fail if the committed files are stale

Nothing outside this script and the schema knows a field offset. If the two
generated files ever disagree about a byte, it is a bug in here rather than a
divergence between two hand-written codecs -- which is the whole point, because
cross-language wire drift shows up as a corrupted field under load rather than
as a compile error.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field as dc_field
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMA_PATH = REPO / "schema" / "market-data.xml"
RUST_OUT = REPO / "crates" / "wire" / "src" / "generated.rs"
CPP_OUT = REPO / "cpp" / "wire" / "include" / "wire" / "generated.hpp"

BANNER_LINES = [
    "@generated by schema/codegen.py from schema/market-data.xml -- do not edit.",
    "",
    "Edit the schema and run `make codegen`. CI regenerates and diffs, so a",
    "hand-edit here fails the build rather than silently surviving.",
]

# ---------------------------------------------------------------------------
# schema model
# ---------------------------------------------------------------------------

PRIMITIVES = {
    "uint8": (1, "u8", "std::uint8_t"),
    "uint16": (2, "u16", "std::uint16_t"),
    "uint32": (4, "u32", "std::uint32_t"),
    "uint64": (8, "u64", "std::uint64_t"),
    "int8": (1, "i8", "std::int8_t"),
    "int16": (2, "i16", "std::int16_t"),
    "int32": (4, "i32", "std::int32_t"),
    "int64": (8, "i64", "std::int64_t"),
}


@dataclass
class Field:
    name: str
    type_name: str
    offset: int
    description: str = ""
    semantic_type: str = ""

    @property
    def is_reserved(self) -> bool:
        return self.name.startswith("reserved")


@dataclass
class Enum:
    name: str
    encoding: str
    values: list[tuple[str, int]]


@dataclass
class Composite:
    name: str
    fields: list[Field]
    description: str = ""

    @property
    def length(self) -> int:
        return max(f.offset + size_of(f.type_name, {}) for f in self.fields)


@dataclass
class Group:
    name: str
    id: int
    block_length: int
    fields: list[Field]
    description: str = ""


@dataclass
class Message:
    name: str
    id: int
    block_length: int
    fields: list[Field]
    description: str = ""
    group: Group | None = None


@dataclass
class Schema:
    package: str
    id: int
    version: int
    semantic_version: str
    byte_order: str
    description: str
    constants: dict[str, str] = dc_field(default_factory=dict)
    enums: dict[str, Enum] = dc_field(default_factory=dict)
    composites: dict[str, Composite] = dc_field(default_factory=dict)
    messages: list[Message] = dc_field(default_factory=list)


def size_of(type_name: str, enums: dict[str, Enum]) -> int:
    if type_name in PRIMITIVES:
        return PRIMITIVES[type_name][0]
    if type_name in enums:
        return PRIMITIVES[enums[type_name].encoding][0]
    raise SchemaError(f"unknown type {type_name!r}")


class SchemaError(Exception):
    pass


def _fields(node: ET.Element) -> list[Field]:
    out = []
    for f in node.findall("field"):
        out.append(
            Field(
                name=f.attrib["name"],
                type_name=f.attrib["type"],
                offset=int(f.attrib["offset"]),
                description=f.attrib.get("description", ""),
                semantic_type=f.attrib.get("semanticType", ""),
            )
        )
    return out


def parse_schema(path: Path = SCHEMA_PATH) -> Schema:
    root = ET.parse(path).getroot()
    schema = Schema(
        package=root.attrib["package"],
        id=int(root.attrib["id"]),
        version=int(root.attrib["version"]),
        semantic_version=root.attrib.get("semanticVersion", ""),
        byte_order=root.attrib.get("byteOrder", "littleEndian"),
        description=root.attrib.get("description", ""),
    )
    if schema.byte_order != "littleEndian":
        raise SchemaError("only littleEndian is supported")

    types = root.find("types")
    if types is None:
        raise SchemaError("schema has no <types>")

    for c in types.findall("constant"):
        schema.constants[c.attrib["name"]] = c.attrib["value"]

    for e in types.findall("enum"):
        values = [(v.attrib["name"], int(v.text.strip())) for v in e.findall("validValue")]
        schema.enums[e.attrib["name"]] = Enum(
            name=e.attrib["name"], encoding=e.attrib["encodingType"], values=values
        )

    for c in types.findall("composite"):
        schema.composites[c.attrib["name"]] = Composite(
            name=c.attrib["name"],
            fields=_fields(c),
            description=c.attrib.get("description", ""),
        )

    for m in root.findall("message"):
        group = None
        g = m.find("group")
        if g is not None:
            group = Group(
                name=g.attrib["name"],
                id=int(g.attrib["id"]),
                block_length=int(g.attrib["blockLength"]),
                fields=_fields(g),
                description=g.attrib.get("description", ""),
            )
        schema.messages.append(
            Message(
                name=m.attrib["name"],
                id=int(m.attrib["id"]),
                block_length=int(m.attrib["blockLength"]),
                fields=_fields(m),
                description=m.attrib.get("description", ""),
                group=group,
            )
        )

    validate(schema)
    return schema


def validate(schema: Schema) -> None:
    """Catch the layout mistakes that would otherwise surface as corrupt fields."""
    for required in ("packetHeader", "messageHeader", "groupSizeEncoding"):
        if required not in schema.composites:
            raise SchemaError(f"schema is missing the {required} composite")

    def check_block(what: str, fields: list[Field], declared: int) -> None:
        if not fields:
            raise SchemaError(f"{what} has no fields")
        seen: dict[int, str] = {}
        for f in fields:
            width = size_of(f.type_name, schema.enums)
            for b in range(f.offset, f.offset + width):
                if b in seen:
                    raise SchemaError(
                        f"{what}: {f.name} overlaps {seen[b]} at byte {b}"
                    )
                seen[b] = f.name
            if f.offset % width != 0:
                raise SchemaError(
                    f"{what}: {f.name} at offset {f.offset} is not {width}-byte aligned "
                    f"within its block"
                )
        extent = max(f.offset + size_of(f.type_name, schema.enums) for f in fields)
        if extent != declared:
            raise SchemaError(
                f"{what}: fields extend to {extent} bytes but blockLength says {declared}. "
                f"Every byte of a block must be named, padding included."
            )

    for c in schema.composites.values():
        check_block(f"composite {c.name}", c.fields, c.length)

    ids: dict[int, str] = {}
    names: set[str] = set()
    for m in schema.messages:
        if m.id in ids:
            raise SchemaError(f"template id {m.id} used by both {ids[m.id]} and {m.name}")
        ids[m.id] = m.name
        if m.name in names:
            raise SchemaError(f"duplicate message name {m.name}")
        names.add(m.name)
        check_block(f"message {m.name}", m.fields, m.block_length)
        if m.group is not None:
            check_block(
                f"message {m.name} group {m.group.name}",
                m.group.fields,
                m.group.block_length,
            )


