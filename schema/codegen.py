def rustfmt(path: Path) -> None:
    exe = shutil.which("rustfmt")
    if exe is None:
        print("  note: rustfmt not found; generated Rust left unformatted", file=sys.stderr)
        return
    subprocess.run([exe, "--edition", "2021", str(path)], check=True)


def write_if_changed(path: Path, text: str, check: bool) -> bool:
    """Returns True when the file on disk already matched."""
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if check:
        if current == text:
            print(f"  ok    {path.relative_to(REPO)}")
            return True
        print(f"  STALE {path.relative_to(REPO)}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"  wrote {path.relative_to(REPO)}")
    return current == text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if a generated file is stale",
    )
    args = ap.parse_args()

    schema = parse_schema()
    print(
        f"schema {schema.package} id={schema.id} version={schema.version} "
        f"-- {len(schema.messages)} messages"
    )

    rust_text = emit_rust(schema)
    cpp_text = emit_cpp(schema)

    if args.check:
        # rustfmt is part of the output, so format a scratch copy before comparing.
        scratch = RUST_OUT.parent / ".generated.check.rs"
        scratch.write_text(rust_text, encoding="utf-8", newline="\n")
        try:
            rustfmt(scratch)
            rust_text = scratch.read_text(encoding="utf-8")
        finally:
            scratch.unlink(missing_ok=True)
        ok = write_if_changed(RUST_OUT, rust_text, True)
        ok = write_if_changed(CPP_OUT, cpp_text, True) and ok
        if not ok:
            print(
                "\ncodegen is stale: run `make codegen` and commit the result",
                file=sys.stderr,
            )
            return 1
        return 0

    write_if_changed(RUST_OUT, rust_text, False)
    rustfmt(RUST_OUT)
    write_if_changed(CPP_OUT, cpp_text, False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
