def cpp_type(type_name: str, schema: Schema) -> str:
    if type_name in PRIMITIVES:
        return PRIMITIVES[type_name][2]
    if type_name in schema.enums:
        return PRIMITIVES[schema.enums[type_name].encoding][2]
    raise SchemaError(f"unknown type {type_name!r}")


def cpp_accessors(
    out: list[str], fields: list[Field], schema: Schema, base: str, indent: str
) -> None:
    for f in fields:
        if f.is_reserved:
            continue
        prim = cpp_type(f.type_name, schema)
        name = snake(f.name)
        is_enum = f.type_name in schema.enums
        if f.description:
            out.append(f"{indent}/// {f.description}")
        if f.semantic_type == "Price":
            out.append(
                f"{indent}/// Fixed point, scaled by 10^{schema.constants['priceExponent']}."
            )
        raw = f"{name}_raw" if is_enum else name
        out.append(
            f"{indent}[[nodiscard]] {prim} {raw}() const noexcept "
            f"{{ return detail::load_le<{prim}>(p_ + {off_expr(base, f.offset)}); }}"
        )
        if is_enum:
            en = pascal(f.type_name)
            out.append(
                f"{indent}/// Validating accessor; returns nullopt on an undefined value."
            )
            out.append(
                f"{indent}[[nodiscard]] std::optional<{en}> {name}() const noexcept "
                f"{{ return {en}_from_raw({raw}()); }}"
            )


