# naming
# ---------------------------------------------------------------------------


def snake(name: str) -> str:
    out = []
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0 and not name[i - 1].isupper():
            out.append("_")
        out.append(ch.lower())
    return "".join(out)


def screaming(name: str) -> str:
    return snake(name).upper()


def pascal(name: str) -> str:
    return name[0].upper() + name[1:]


def singular(name: str) -> str:
    return name[:-1] if name.endswith("s") else name


def off_expr(base: str, offset: int) -> str:
    """`base + offset` without the `+ 0` that clippy's identity_op rejects."""
    if offset == 0:
        return base
    if base == "0":
        return str(offset)
    return f"{base} + {offset}"


# ---------------------------------------------------------------------------
# Rust emitter
# ---------------------------------------------------------------------------


def rust_type(type_name: str, schema: Schema) -> str:
    if type_name in PRIMITIVES:
        return PRIMITIVES[type_name][1]
    if type_name in schema.enums:
        return PRIMITIVES[schema.enums[type_name].encoding][1]
    raise SchemaError(f"unknown type {type_name!r}")


def rust_accessors(
    out: list[str],
    fields: list[Field],
    schema: Schema,
    base: str,
    indent: str = "    ",
) -> None:
    """Emit read accessors for one block. `base` is a Rust expression for the
    byte offset of the block within `self.buf`."""
    for f in fields:
        if f.is_reserved:
            continue
        prim = rust_type(f.type_name, schema)
        name = snake(f.name)
        doc = f.description
        is_enum = f.type_name in schema.enums
        if doc:
            out.append(f"{indent}/// {doc}")
        if f.semantic_type == "Price":
            out.append(
                f"{indent}/// Fixed point, scaled by 10^{schema.constants['priceExponent']}."
            )
        raw_name = f"{name}_raw" if is_enum else name
        out.append(f"{indent}#[inline(always)]")
        out.append(f"{indent}pub fn {raw_name}(&self) -> {prim} {{")
        out.append(f"{indent}    le_{prim}(self.buf, {off_expr(base, f.offset)})")
        out.append(f"{indent}}}")
        out.append("")
        if is_enum:
            enum_name = pascal(f.type_name)
            out.append(f"{indent}/// Validating accessor. Use `{raw_name}()` on the hot path.")
            out.append(f"{indent}#[inline]")
            out.append(
                f"{indent}pub fn {name}(&self) -> Result<{enum_name}, WireError> {{"
            )
            out.append(f"{indent}    {enum_name}::from_{prim}(self.{raw_name}())")
            out.append(f"{indent}}}")
            out.append("")


def rust_param_list(fields: list[Field], schema: Schema) -> list[tuple[str, str, Field]]:
    params = []
    for f in fields:
        if f.is_reserved:
            continue
        if f.type_name in schema.enums:
            params.append((snake(f.name), pascal(f.type_name), f))
        else:
            params.append((snake(f.name), rust_type(f.type_name, schema), f))
    return params


def rust_write_field(
    out: list[str], f: Field, schema: Schema, base: str, indent: str, buf: str = "buf"
) -> None:
    prim = rust_type(f.type_name, schema)
    name = snake(f.name)
    value = f"{name} as {prim}" if f.type_name in schema.enums else name
    out.append(f"{indent}put_{prim}({buf}, {off_expr(base, f.offset)}, {value});")


def used_rust_prims(schema: Schema) -> list[str]:
    """Only emit the little-endian helpers the schema actually uses; an unused
    private fn is a dead_code warning, and this crate builds with -D warnings."""
    used = {"u16"}  # both framing headers are u16-only
    blocks: list[list[Field]] = [c.fields for c in schema.composites.values()]
    for m in schema.messages:
        blocks.append(m.fields)
        if m.group is not None:
            blocks.append(m.group.fields)
    for fields in blocks:
        for f in fields:
            used.add(rust_type(f.type_name, schema))
    order = ["u8", "i8", "u16", "i16", "u32", "i32", "u64", "i64"]
    return [t for t in order if t in used]


def emit_rust(schema: Schema) -> str:
    o: list[str] = []
    for line in BANNER_LINES:
        o.append(f"//! {line}" if line else "//!")
    o.append("")
    o.append("#![allow(clippy::too_many_arguments)]")
    o.append("")
    o.append("use crate::error::WireError;")
    o.append("")

    ph = schema.composites["packetHeader"]
    mh = schema.composites["messageHeader"]
    gse = schema.composites["groupSizeEncoding"]

    o.append("/// Schema identity, checked on every datagram.")
    o.append(f"pub const SCHEMA_ID: u16 = {schema.id};")
    o.append(f"pub const SCHEMA_VERSION: u16 = {schema.version};")
    o.append(f'pub const SEMANTIC_VERSION: &str = "{schema.semantic_version}";')
    o.append("")
    for k, v in schema.constants.items():
        o.append(f"/// Schema constant `{k}`.")
        o.append(f"pub const {screaming(k)}: i8 = {v};")
    o.append("")
    o.append("/// Bytes of per-datagram framing.")
    o.append(f"pub const PACKET_HEADER_LEN: usize = {ph.length};")
    o.append("/// Bytes of per-message framing.")
    o.append(f"pub const MESSAGE_HEADER_LEN: usize = {mh.length};")
    o.append("/// Bytes of per-group framing.")
    o.append(f"pub const GROUP_SIZE_ENCODING_LEN: usize = {gse.length};")
    o.append("")
    o.append("/// `packetHeader.flags` bit 0: this datagram belongs to a snapshot cycle.")
    o.append("pub const PACKET_FLAG_SNAPSHOT: u8 = 0x01;")
    o.append("")

    # --- little-endian helpers -------------------------------------------
    o.append("// Unaligned-safe little-endian access. Messages are packed back to back")
    o.append("// inside a datagram, so a block can start at any byte offset; every read")
    o.append("// and write below goes through a fixed-size copy, which the compiler")
    o.append("// lowers to a single instruction on x86-64 and aarch64.")
    for t in used_rust_prims(schema):
        width = int(t[1:]) // 8
        o.append("#[inline(always)]")
        o.append(f"fn le_{t}(b: &[u8], o: usize) -> {t} {{")
        if t == "u8":
            o.append("    b[o]")
        elif width == 1:
            o.append(f"    b[o] as {t}")
        else:
            o.append(f"    let mut a = [0u8; {width}];")
            o.append(f"    a.copy_from_slice(&b[o..o + {width}]);")
            o.append(f"    {t}::from_le_bytes(a)")
        o.append("}")
        o.append("")
        o.append("#[inline(always)]")
        o.append(f"fn put_{t}(b: &mut [u8], o: usize, v: {t}) {{")
        if t == "u8":
            o.append("    b[o] = v;")
        elif width == 1:
            o.append("    b[o] = v as u8;")
        else:
            o.append(f"    b[o..o + {width}].copy_from_slice(&v.to_le_bytes());")
        o.append("}")
        o.append("")

    # --- enums ------------------------------------------------------------
    for e in schema.enums.values():
        prim = PRIMITIVES[e.encoding][1]
        o.append(f"/// `{e.name}` as encoded on the wire.")
        o.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
        o.append(f"#[repr({prim})]")
        o.append(f"pub enum {pascal(e.name)} {{")
        for vname, vval in e.values:
            o.append(f"    {pascal(vname)} = {vval},")
        o.append("}")
        o.append("")
        o.append(f"impl {pascal(e.name)} {{")
        o.append("    /// Reject anything the schema does not define rather than")
        o.append("    /// transmuting an unknown discriminant.")
        o.append("    #[inline]")
        o.append(f"    pub fn from_{prim}(v: {prim}) -> Result<Self, WireError> {{")
        o.append("        match v {")
        for vname, vval in e.values:
            o.append(f"            {vval} => Ok(Self::{pascal(vname)}),")
        o.append(
            f'            other => Err(WireError::InvalidEnum {{ name: "{e.name}", value: other as u64 }}),'
        )
        o.append("        }")
        o.append("    }")
        o.append("")
        o.append("    #[inline(always)]")
        o.append(f"    pub fn to_{prim}(self) -> {prim} {{")
        o.append(f"        self as {prim}")
        o.append("    }")
        o.append("}")
        o.append("")

    # --- template ids -----------------------------------------------------
    o.append("/// Template ids, as they appear in `messageHeader.templateId`.")
    o.append("pub mod template {")
    for m in schema.messages:
        o.append(f"    /// {m.description}")
        o.append(f"    pub const {screaming(m.name)}: u16 = {m.id};")
    o.append("}")
    o.append("")

    # --- packet header ----------------------------------------------------
    o.append("/// Read-only view over the 24-byte datagram header.")
    o.append("#[derive(Debug, Clone, Copy)]")
    o.append("pub struct PacketHeaderDecoder<'a> {")
    o.append("    buf: &'a [u8],")
    o.append("}")
    o.append("")
    o.append("impl<'a> PacketHeaderDecoder<'a> {")
    o.append("    /// Wraps a datagram. Fails on a short buffer or a foreign schema,")
    o.append("    /// which is the only place a wrong-feed datagram gets rejected.")
    o.append("    #[inline]")
    o.append("    pub fn wrap(buf: &'a [u8]) -> Result<Self, WireError> {")
    o.append("        if buf.len() < PACKET_HEADER_LEN {")
    o.append("            return Err(WireError::ShortBuffer {")
    o.append("                needed: PACKET_HEADER_LEN,")
    o.append("                got: buf.len(),")
    o.append("            });")
    o.append("        }")
    o.append("        let d = Self { buf };")
    o.append("        if d.schema_id() != SCHEMA_ID {")
    o.append("            return Err(WireError::SchemaMismatch {")
    o.append("                expected: SCHEMA_ID,")
    o.append("                got: d.schema_id(),")
    o.append("            });")
    o.append("        }")
    o.append("        Ok(d)")
    o.append("    }")
    o.append("")
    rust_accessors(o, ph.fields, schema, "0")
    o.append("    /// True when this datagram is part of a snapshot cycle.")
    o.append("    #[inline(always)]")
    o.append("    pub fn is_snapshot(&self) -> bool {")
    o.append("        self.flags() & PACKET_FLAG_SNAPSHOT != 0")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append("/// Writes the datagram header. `message_count` is patched by")
    o.append("/// [`patch_message_count`] once the messages have been written.")
    o.append("#[inline]")
    o.append("pub fn encode_packet_header(")
    o.append("    buf: &mut [u8],")
    for f in ph.fields:
        if f.name in ("schemaId", "version", "messageCount"):
            continue
        o.append(f"    {snake(f.name)}: {rust_type(f.type_name, schema)},")
    o.append(") -> Result<usize, WireError> {")
    o.append("    if buf.len() < PACKET_HEADER_LEN {")
    o.append("        return Err(WireError::ShortBuffer {")
    o.append("            needed: PACKET_HEADER_LEN,")
    o.append("            got: buf.len(),")
    o.append("        });")
    o.append("    }")
    o.append("    buf[..PACKET_HEADER_LEN].fill(0);")
    for f in ph.fields:
        if f.name == "schemaId":
            o.append(f"    put_u16(buf, {f.offset}, SCHEMA_ID);")
        elif f.name == "version":
            o.append(f"    put_u16(buf, {f.offset}, SCHEMA_VERSION);")
        elif f.name == "messageCount":
            o.append(f"    put_u16(buf, {f.offset}, 0);")
        else:
            rust_write_field(o, f, schema, "0", "    ")
    o.append("    Ok(PACKET_HEADER_LEN)")
    o.append("}")
    o.append("")
    mc_off = next(f.offset for f in ph.fields if f.name == "messageCount")
    o.append("/// Patches `messageCount` in a header written by [`encode_packet_header`].")
    o.append("#[inline]")
    o.append("pub fn patch_message_count(buf: &mut [u8], count: u16) -> Result<(), WireError> {")
    o.append("    if buf.len() < PACKET_HEADER_LEN {")
    o.append("        return Err(WireError::ShortBuffer {")
    o.append("            needed: PACKET_HEADER_LEN,")
    o.append("            got: buf.len(),")
    o.append("        });")
    o.append("    }")
    o.append(f"    put_u16(buf, {mc_off}, count);")
    o.append("    Ok(())")
    o.append("}")
    o.append("")

    # --- message header ---------------------------------------------------
    o.append("/// Read-only view over the 8-byte message header.")
    o.append("#[derive(Debug, Clone, Copy)]")
    o.append("pub struct MessageHeaderDecoder<'a> {")
    o.append("    buf: &'a [u8],")
    o.append("}")
    o.append("")
    o.append("impl<'a> MessageHeaderDecoder<'a> {")
    o.append("    #[inline]")
    o.append("    pub fn wrap(buf: &'a [u8]) -> Result<Self, WireError> {")
    o.append("        if buf.len() < MESSAGE_HEADER_LEN {")
    o.append("            return Err(WireError::ShortBuffer {")
    o.append("                needed: MESSAGE_HEADER_LEN,")
    o.append("                got: buf.len(),")
    o.append("            });")
    o.append("        }")
    o.append("        Ok(Self { buf })")
    o.append("    }")
    o.append("")
    rust_accessors(o, mh.fields, schema, "0")
    o.append("}")
    o.append("")
    o.append("#[inline(always)]")
    o.append("fn write_message_header(buf: &mut [u8], block_length: u16, template_id: u16) {")
    for f in mh.fields:
        src = {
            "blockLength": "block_length",
            "templateId": "template_id",
            "schemaId": "SCHEMA_ID",
            "version": "SCHEMA_VERSION",
        }[f.name]
        o.append(f"    put_u16(buf, {f.offset}, {src});")
    o.append("}")
    o.append("")

    # --- per-message decoders and encoders --------------------------------
    for m in schema.messages:
        emit_rust_message(o, m, schema)

    # --- dispatch ---------------------------------------------------------
    o.append("/// One decoded message, still borrowing the datagram buffer.")
    o.append("#[derive(Debug, Clone, Copy)]")
    o.append("pub enum Message<'a> {")
    for m in schema.messages:
        o.append(f"    {m.name}({m.name}Decoder<'a>),")
    o.append("}")
    o.append("")
    o.append("impl<'a> Message<'a> {")
    o.append("    /// Total bytes this message occupies, header included.")
    o.append("    #[inline(always)]")
    o.append("    pub fn total_len(&self) -> usize {")
    o.append("        match self {")
    for m in schema.messages:
        o.append(f"            Self::{m.name}(d) => d.total_len(),")
    o.append("        }")
    o.append("    }")
    o.append("")
    o.append("    #[inline(always)]")
    o.append("    pub fn template_id(&self) -> u16 {")
    o.append("        match self {")
    for m in schema.messages:
        o.append(f"            Self::{m.name}(_) => template::{screaming(m.name)},")
    o.append("        }")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append("/// Decodes the message starting at `buf[0]`.")
    o.append("#[inline]")
    o.append("pub fn decode_message(buf: &[u8]) -> Result<Message<'_>, WireError> {")
    o.append("    let hdr = MessageHeaderDecoder::wrap(buf)?;")
    o.append("    if hdr.schema_id() != SCHEMA_ID {")
    o.append("        return Err(WireError::SchemaMismatch {")
    o.append("            expected: SCHEMA_ID,")
    o.append("            got: hdr.schema_id(),")
    o.append("        });")
    o.append("    }")
    o.append("    match hdr.template_id() {")
    for m in schema.messages:
        o.append(
            f"        template::{screaming(m.name)} => "
            f"Ok(Message::{m.name}({m.name}Decoder::wrap(buf)?)),"
        )
    o.append("        other => Err(WireError::UnknownTemplate(other)),")
    o.append("    }")
    o.append("}")
    o.append("")

    emit_rust_packet_reader(o, schema)
    emit_rust_packet_writer(o, schema)

    return "\n".join(o).rstrip() + "\n"


def emit_rust_message(o: list[str], m: Message, schema: Schema) -> None:
    dec = f"{m.name}Decoder"
    o.append(f"// --- {m.name} " + "-" * max(0, 62 - len(m.name)))
    o.append("")
    o.append(f"/// {m.description}")
    o.append("///")
    o.append("/// Borrows the datagram; decoding copies nothing.")
    o.append("#[derive(Debug, Clone, Copy)]")
    o.append(f"pub struct {dec}<'a> {{")
    o.append("    buf: &'a [u8],")
    o.append("    root_len: usize,")
    o.append("}")
    o.append("")
    o.append(f"impl<'a> {dec}<'a> {{")
    o.append(f"    pub const TEMPLATE_ID: u16 = {m.id};")
    o.append(f"    pub const BLOCK_LENGTH: u16 = {m.block_length};")
    o.append("")
    o.append("    /// Wraps a buffer whose first byte is the message header.")
    o.append("    ///")
    o.append("    /// The root block length comes from the wire, not from the constant,")
    o.append("    /// so a newer publisher that appended fields is skipped correctly")
    o.append("    /// rather than misparsed.")
    o.append("    #[inline]")
    o.append("    pub fn wrap(buf: &'a [u8]) -> Result<Self, WireError> {")
    o.append("        let hdr = MessageHeaderDecoder::wrap(buf)?;")
    o.append("        if hdr.template_id() != Self::TEMPLATE_ID {")
    o.append("            return Err(WireError::TemplateMismatch {")
    o.append("                expected: Self::TEMPLATE_ID,")
    o.append("                got: hdr.template_id(),")
    o.append("            });")
    o.append("        }")
    o.append("        let root_len = hdr.block_length() as usize;")
    o.append("        if root_len < Self::BLOCK_LENGTH as usize {")
    o.append("            return Err(WireError::BlockTooSmall {")
    o.append('                message: "' + m.name + '",')
    o.append("                needed: Self::BLOCK_LENGTH,")
    o.append("                got: hdr.block_length(),")
    o.append("            });")
    o.append("        }")
    o.append("        let need = MESSAGE_HEADER_LEN + root_len;")
    o.append("        if buf.len() < need {")
    o.append("            return Err(WireError::ShortBuffer {")
    o.append("                needed: need,")
    o.append("                got: buf.len(),")
    o.append("            });")
    o.append("        }")
    o.append("        let d = Self { buf, root_len };")
    if m.group is not None:
        o.append("        // The group header has to be proved present before it can be")
        o.append("        // read: `total_len` reads it, so calling that first on a")
        o.append("        // truncated datagram would panic instead of returning an error.")
        o.append("        let with_group_header = need + GROUP_SIZE_ENCODING_LEN;")
        o.append("        if buf.len() < with_group_header {")
        o.append("            return Err(WireError::ShortBuffer {")
        o.append("                needed: with_group_header,")
        o.append("                got: buf.len(),")
        o.append("            });")
        o.append("        }")
        o.append("        // Now the entry count is readable, so the full extent is known.")
        o.append("        let total = d.total_len();")
        o.append("        if buf.len() < total {")
        o.append("            return Err(WireError::ShortBuffer {")
        o.append("                needed: total,")
        o.append("                got: buf.len(),")
        o.append("            });")
        o.append("        }")
    o.append("        Ok(d)")
    o.append("    }")
    o.append("")
    rust_accessors(o, m.fields, schema, "MESSAGE_HEADER_LEN")

    if m.group is None:
        o.append("    /// Total bytes, header included.")
        o.append("    #[inline(always)]")
        o.append("    pub fn total_len(&self) -> usize {")
        o.append("        MESSAGE_HEADER_LEN + self.root_len")
        o.append("    }")
        o.append("}")
        o.append("")
        emit_rust_plain_encoder(o, m, schema)
    else:
        g = m.group
        entry = f"{m.name}{pascal(singular(g.name))}Decoder"
        gse_off = "MESSAGE_HEADER_LEN + self.root_len"
        o.append(f"    /// Bytes per entry of the `{g.name}` group, read from the wire.")
        o.append("    #[inline(always)]")
        o.append(f"    pub fn {snake(g.name)}_block_length(&self) -> u16 {{")
        o.append(f"        le_u16(self.buf, {gse_off})")
        o.append("    }")
        o.append("")
        o.append(f"    /// Number of `{g.name}` entries.")
        o.append("    #[inline(always)]")
        o.append(f"    pub fn {snake(g.name)}_count(&self) -> u16 {{")
        o.append(f"        le_u16(self.buf, {gse_off} + 2)")
        o.append("    }")
        o.append("")
        o.append(f"    /// Iterates the `{g.name}` group. {g.description}")
        o.append("    #[inline]")
        o.append(f"    pub fn {snake(g.name)}(&self) -> {m.name}{pascal(g.name)}Iter<'a> {{")
        o.append(f"        {m.name}{pascal(g.name)}Iter {{")
        o.append(f"            buf: self.buf,")
        o.append(f"            pos: {gse_off} + GROUP_SIZE_ENCODING_LEN,")
        o.append(f"            block_len: self.{snake(g.name)}_block_length() as usize,")
        o.append(f"            remaining: self.{snake(g.name)}_count(),")
        o.append("        }")
        o.append("    }")
        o.append("")
        o.append("    /// Total bytes, header and group included.")
        o.append("    #[inline(always)]")
        o.append("    pub fn total_len(&self) -> usize {")
        o.append(f"        MESSAGE_HEADER_LEN")
        o.append("            + self.root_len")
        o.append("            + GROUP_SIZE_ENCODING_LEN")
        o.append(
            f"            + self.{snake(g.name)}_count() as usize "
            f"* self.{snake(g.name)}_block_length() as usize"
        )
        o.append("    }")
        o.append("}")
        o.append("")
        # group entry decoder
        o.append(f"/// One entry of the `{m.name}.{g.name}` group.")
        o.append("#[derive(Debug, Clone, Copy)]")
        o.append(f"pub struct {entry}<'a> {{")
        o.append("    buf: &'a [u8],")
        o.append("}")
        o.append("")
        o.append(f"impl<'a> {entry}<'a> {{")
        o.append(f"    pub const BLOCK_LENGTH: u16 = {g.block_length};")
        o.append("")
        rust_accessors(o, g.fields, schema, "0")
        o.append("}")
        o.append("")
        o.append(f"/// Iterator over `{m.name}.{g.name}`.")
        o.append("#[derive(Debug, Clone, Copy)]")
        o.append(f"pub struct {m.name}{pascal(g.name)}Iter<'a> {{")
        o.append("    buf: &'a [u8],")
        o.append("    pos: usize,")
        o.append("    block_len: usize,")
        o.append("    remaining: u16,")
        o.append("}")
        o.append("")
        o.append(f"impl<'a> Iterator for {m.name}{pascal(g.name)}Iter<'a> {{")
        o.append(f"    type Item = {entry}<'a>;")
        o.append("")
        o.append("    #[inline]")
        o.append("    fn next(&mut self) -> Option<Self::Item> {")
        o.append("        if self.remaining == 0 {")
        o.append("            return None;")
        o.append("        }")
        o.append("        self.remaining -= 1;")
        o.append("        let start = self.pos;")
        o.append("        self.pos += self.block_len;")
        o.append(f"        Some({entry} {{")
        o.append("            buf: &self.buf[start..self.pos],")
        o.append("        })")
        o.append("    }")
        o.append("")
        o.append("    #[inline]")
        o.append("    fn size_hint(&self) -> (usize, Option<usize>) {")
        o.append("        (self.remaining as usize, Some(self.remaining as usize))")
        o.append("    }")
        o.append("}")
        o.append("")
        o.append(
            f"impl<'a> ExactSizeIterator for {m.name}{pascal(g.name)}Iter<'a> {{}}"
        )
        o.append("")
        emit_rust_group_encoder(o, m, schema)


def emit_rust_plain_encoder(o: list[str], m: Message, schema: Schema) -> None:
    params = rust_param_list(m.fields, schema)
    o.append(f"/// Encodes a `{m.name}` at `buf[0]`, header included.")
    o.append("///")
    o.append("/// Returns the bytes written. Reserved bytes are zeroed, which is what")
    o.append("/// makes a re-encode byte-identical to the golden vector.")
    o.append("#[inline]")
    o.append(f"pub fn encode_{snake(m.name)}(")
    o.append("    buf: &mut [u8],")
    for name, ty, _ in params:
        o.append(f"    {name}: {ty},")
    o.append(") -> Result<usize, WireError> {")
    o.append(f"    const LEN: usize = MESSAGE_HEADER_LEN + {m.block_length};")
    o.append("    if buf.len() < LEN {")
    o.append("        return Err(WireError::ShortBuffer {")
    o.append("            needed: LEN,")
    o.append("            got: buf.len(),")
    o.append("        });")
    o.append("    }")
    o.append("    buf[..LEN].fill(0);")
    o.append(
        f"    write_message_header(buf, {m.block_length}, template::{screaming(m.name)});"
    )
    for f in m.fields:
        if f.is_reserved:
            continue
        rust_write_field(o, f, schema, "MESSAGE_HEADER_LEN", "    ")
    o.append("    Ok(LEN)")
    o.append("}")
    o.append("")


def emit_rust_group_encoder(o: list[str], m: Message, schema: Schema) -> None:
    g = m.group
    assert g is not None
    enc = f"{m.name}Encoder"
    root_params = rust_param_list(m.fields, schema)
    entry_params = rust_param_list(g.fields, schema)
    o.append(f"/// Two-phase encoder for `{m.name}`, which carries a repeating group.")
    o.append("///")
    o.append("/// Writes straight into a caller-owned buffer: `start`, then one")
    o.append(f"/// `push_{snake(singular(g.name))}` per entry, then `finish`. No allocation anywhere.")
    o.append("#[derive(Debug)]")
    o.append(f"pub struct {enc}<'a> {{")
    o.append("    buf: &'a mut [u8],")
    o.append("    pos: usize,")
    o.append("    count: u16,")
    o.append("}")
    o.append("")
    o.append(f"impl<'a> {enc}<'a> {{")
    o.append("    #[inline]")
    o.append("    pub fn start(")
    o.append("        buf: &'a mut [u8],")
    for name, ty, _ in root_params:
        o.append(f"        {name}: {ty},")
    o.append("    ) -> Result<Self, WireError> {")
    o.append(
        f"        const HEAD: usize = MESSAGE_HEADER_LEN + {m.block_length} + GROUP_SIZE_ENCODING_LEN;"
    )
    o.append("        if buf.len() < HEAD {")
    o.append("            return Err(WireError::ShortBuffer {")
    o.append("                needed: HEAD,")
    o.append("                got: buf.len(),")
    o.append("            });")
    o.append("        }")
    o.append("        buf[..HEAD].fill(0);")
    o.append(
        f"        write_message_header(buf, {m.block_length}, template::{screaming(m.name)});"
    )
    for f in m.fields:
        if f.is_reserved:
            continue
        rust_write_field(o, f, schema, "MESSAGE_HEADER_LEN", "        ")
    o.append(
        f"        put_u16(buf, MESSAGE_HEADER_LEN + {m.block_length}, {g.block_length});"
    )
    o.append("        Ok(Self {")
    o.append("            buf,")
    o.append("            pos: HEAD,")
    o.append("            count: 0,")
    o.append("        })")
    o.append("    }")
    o.append("")
    o.append(f"    /// Appends one `{g.name}` entry.")
    o.append("    #[inline]")
    o.append(f"    pub fn push_{snake(singular(g.name))}(")
    o.append("        &mut self,")
    for name, ty, _ in entry_params:
        o.append(f"        {name}: {ty},")
    o.append("    ) -> Result<(), WireError> {")
    o.append(f"        const ENTRY: usize = {g.block_length};")
    o.append("        if self.buf.len() < self.pos + ENTRY {")
    o.append("            return Err(WireError::ShortBuffer {")
    o.append("                needed: self.pos + ENTRY,")
    o.append("                got: self.buf.len(),")
    o.append("            });")
    o.append("        }")
    o.append("        if self.count == u16::MAX {")
    o.append("            return Err(WireError::GroupOverflow {")
    o.append('                group: "' + g.name + '",')
    o.append("            });")
    o.append("        }")
    o.append("        let base = self.pos;")
    o.append("        self.buf[base..base + ENTRY].fill(0);")
    for f in g.fields:
        if f.is_reserved:
            continue
        rust_write_field(o, f, schema, "base", "        ", buf="self.buf")
    o.append("        self.pos += ENTRY;")
    o.append("        self.count += 1;")
    o.append("        Ok(())")
    o.append("    }")
    o.append("")
    o.append("    /// Patches the group count and returns the total bytes written.")
    o.append("    #[inline]")
    o.append("    pub fn finish(self) -> usize {")
    o.append(
        f"        put_u16(self.buf, MESSAGE_HEADER_LEN + {m.block_length} + 2, self.count);"
    )
    o.append("        self.pos")
    o.append("    }")
    o.append("}")
    o.append("")


def emit_rust_packet_reader(o: list[str], schema: Schema) -> None:
    o.append("/// Walks the messages in one datagram.")
    o.append("///")
    o.append("/// The sequence of message `i` is `firstSequence + i`; nothing on the wire")
    o.append("/// repeats it, which is what keeps the per-message framing at 8 bytes.")
    o.append("#[derive(Debug, Clone, Copy)]")
    o.append("pub struct PacketReader<'a> {")
    o.append("    buf: &'a [u8],")
    o.append("    header: PacketHeaderDecoder<'a>,")
    o.append("}")
    o.append("")
    o.append("impl<'a> PacketReader<'a> {")
    o.append("    #[inline]")
    o.append("    pub fn new(buf: &'a [u8]) -> Result<Self, WireError> {")
    o.append("        let header = PacketHeaderDecoder::wrap(buf)?;")
    o.append("        Ok(Self { buf, header })")
    o.append("    }")
    o.append("")
    o.append("    #[inline(always)]")
    o.append("    pub fn header(&self) -> PacketHeaderDecoder<'a> {")
    o.append("        self.header")
    o.append("    }")
    o.append("")
    o.append("    #[inline]")
    o.append("    pub fn messages(&self) -> PacketMessageIter<'a> {")
    o.append("        PacketMessageIter {")
    o.append("            buf: self.buf,")
    o.append("            pos: PACKET_HEADER_LEN,")
    o.append("            sequence: self.header.first_sequence(),")
    o.append("            remaining: self.header.message_count(),")
    o.append("            failed: false,")
    o.append("        }")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append("/// Yields `(sequence, message)` pairs, or the first decode error and")
    o.append("/// then nothing -- a truncated datagram must not look like a short one.")
    o.append("#[derive(Debug, Clone, Copy)]")
    o.append("pub struct PacketMessageIter<'a> {")
    o.append("    buf: &'a [u8],")
    o.append("    pos: usize,")
    o.append("    sequence: u64,")
    o.append("    remaining: u16,")
    o.append("    failed: bool,")
    o.append("}")
    o.append("")
    o.append("impl<'a> Iterator for PacketMessageIter<'a> {")
    o.append("    type Item = Result<(u64, Message<'a>), WireError>;")
    o.append("")
    o.append("    #[inline]")
    o.append("    fn next(&mut self) -> Option<Self::Item> {")
    o.append("        if self.failed || self.remaining == 0 {")
    o.append("            return None;")
    o.append("        }")
    o.append("        match decode_message(&self.buf[self.pos..]) {")
    o.append("            Ok(msg) => {")
    o.append("                let seq = self.sequence;")
    o.append("                self.pos += msg.total_len();")
    o.append("                self.sequence += 1;")
    o.append("                self.remaining -= 1;")
    o.append("                Some(Ok((seq, msg)))")
    o.append("            }")
    o.append("            Err(e) => {")
    o.append("                self.failed = true;")
    o.append("                Some(Err(e))")
    o.append("            }")
    o.append("        }")
    o.append("    }")
    o.append("}")
    o.append("")


def emit_rust_packet_writer(o: list[str], schema: Schema) -> None:
    mc_off = next(
        f.offset
        for f in schema.composites["packetHeader"].fields
        if f.name == "messageCount"
    )
    o.append("/// Packs messages into one datagram buffer.")
    o.append("///")
    o.append("/// Batching is not a detail here: at one message per datagram the kernel")
    o.append("/// UDP path is the ceiling, so the publisher packs many messages behind a")
    o.append("/// single header and reads the clock once. See docs/WIRE.md.")
    o.append("#[derive(Debug)]")
    o.append("pub struct PacketWriter<'a> {")
    o.append("    buf: &'a mut [u8],")
    o.append("    pos: usize,")
    o.append("    count: u16,")
    o.append("}")
    o.append("")
    o.append("impl<'a> PacketWriter<'a> {")
    o.append("    #[inline]")
    o.append("    pub fn new(")
    o.append("        buf: &'a mut [u8],")
    ph = schema.composites["packetHeader"]
    for f in ph.fields:
        if f.name in ("schemaId", "version", "messageCount"):
            continue
        o.append(f"        {snake(f.name)}: {rust_type(f.type_name, schema)},")
    o.append("    ) -> Result<Self, WireError> {")
    args = ", ".join(
        snake(f.name)
        for f in ph.fields
        if f.name not in ("schemaId", "version", "messageCount")
    )
    o.append(f"        encode_packet_header(buf, {args})?;")
    o.append("        Ok(Self {")
    o.append("            buf,")
    o.append("            pos: PACKET_HEADER_LEN,")
    o.append("            count: 0,")
    o.append("        })")
    o.append("    }")
    o.append("")
    o.append("    /// Bytes still free in the datagram.")
    o.append("    #[inline(always)]")
    o.append("    pub fn remaining(&self) -> usize {")
    o.append("        self.buf.len() - self.pos")
    o.append("    }")
    o.append("")
    o.append("    #[inline(always)]")
    o.append("    pub fn message_count(&self) -> u16 {")
    o.append("        self.count")
    o.append("    }")
    o.append("")
    o.append("    /// The unwritten tail, for encoders that write themselves.")
    o.append("    #[inline(always)]")
    o.append("    pub fn tail(&mut self) -> &mut [u8] {")
    o.append("        &mut self.buf[self.pos..]")
    o.append("    }")
    o.append("")
    o.append("    /// Records `n` bytes written into [`tail`](Self::tail) as one message.")
    o.append("    #[inline]")
    o.append("    pub fn commit(&mut self, n: usize) -> Result<(), WireError> {")
    o.append("        if self.pos + n > self.buf.len() {")
    o.append("            return Err(WireError::ShortBuffer {")
    o.append("                needed: self.pos + n,")
    o.append("                got: self.buf.len(),")
    o.append("            });")
    o.append("        }")
    o.append("        if self.count == u16::MAX {")
    o.append('            return Err(WireError::GroupOverflow { group: "packet" });')
    o.append("        }")
    o.append("        self.pos += n;")
    o.append("        self.count += 1;")
    o.append("        Ok(())")
    o.append("    }")
    o.append("")
    for m in schema.messages:
        if m.group is not None:
            continue
        params = rust_param_list(m.fields, schema)
        o.append(f"    /// Appends a `{m.name}`.")
        o.append("    #[inline]")
        o.append(f"    pub fn {snake(m.name)}(")
        o.append("        &mut self,")
        for name, ty, _ in params:
            o.append(f"        {name}: {ty},")
        o.append("    ) -> Result<(), WireError> {")
        call = ", ".join(name for name, _, _ in params)
        o.append(f"        let n = encode_{snake(m.name)}(&mut self.buf[self.pos..], {call})?;")
        o.append("        self.pos += n;")
        o.append("        self.count += 1;")
        o.append("        Ok(())")
        o.append("    }")
        o.append("")
    o.append("    /// Patches `messageCount` and returns the datagram length.")
    o.append("    #[inline]")
    o.append("    pub fn finish(self) -> usize {")
    o.append("        let count = self.count;")
    o.append("        let pos = self.pos;")
    o.append("        // `new` wrote the header, so the buffer is known long enough.")
    o.append(f"        put_u16(self.buf, {mc_off}, count);")
    o.append("        pos")
    o.append("    }")
    o.append("}")
    o.append("")


