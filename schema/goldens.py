# message model
# ---------------------------------------------------------------------------


@dataclass
class Msg:
    """One message: its wire bytes plus the field values both suites assert."""

    kind: str
    fields: dict[str, object]
    orders: list[dict[str, object]] = dc_field(default_factory=list)

    def pack(self) -> bytes:
        f = self.fields
        h = msg_header(self.kind)
        if self.kind == "AddOrder":
            return h + struct.pack(
                FMT_ADD_ORDER,
                f["order_id"], f["price"], f["quantity"], f["symbol_id"], f["side"], 0,
            )
        if self.kind == "ModifyOrder":
            return h + struct.pack(
                FMT_MODIFY_ORDER,
                f["order_id"], f["new_price"], f["new_quantity"], f["symbol_id"],
                f["side"], f["reason"],
            )
        if self.kind == "DeleteOrder":
            return h + struct.pack(
                FMT_DELETE_ORDER, f["order_id"], f["symbol_id"], f["side"], 0
            )
        if self.kind == "Trade":
            return h + struct.pack(
                FMT_TRADE,
                f["trade_id"], f["aggressor_order_id"], f["resting_order_id"],
                f["price"], f["quantity"], f["symbol_id"], f["aggressor_side"], 0,
            )
        if self.kind == "Heartbeat":
            return h + struct.pack(FMT_HEARTBEAT, f["last_sequence"])
        if self.kind == "SequenceReset":
            return h + struct.pack(FMT_SEQUENCE_RESET, f["new_sequence"])
        if self.kind == "Snapshot":
            body = struct.pack(
                FMT_SNAPSHOT, f["last_sequence"], f["symbol_id"], f["flags"], 0
            )
            group = struct.pack(FMT_GROUP_HEADER, ORDER_BLOCK_LENGTH, len(self.orders))
            for o in self.orders:
                group += struct.pack(
                    FMT_SNAPSHOT_ORDER,
                    o["order_id"], o["price"], o["quantity"], o["side"], 0, 0,
                )
            return h + body + group
        raise AssertionError(f"unhandled message kind {self.kind}")


@dataclass
class Vector:
    name: str
    why: str
    channel: int
    flags: int
    first_sequence: int
    send_timestamp_ns: int
    messages: list[Msg]

    def pack(self) -> bytes:
        body = b"".join(m.pack() for m in self.messages)
        head = struct.pack(
            FMT_PACKET_HEADER,
            SCHEMA_ID, SCHEMA_VERSION, len(self.messages),
            self.channel, self.flags, self.first_sequence, self.send_timestamp_ns,
        )
        return head + body


