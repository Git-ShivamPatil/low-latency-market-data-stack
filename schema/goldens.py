# ---------------------------------------------------------------------------
# the layout, transcribed by hand from docs/WIRE.md
# ---------------------------------------------------------------------------

FMT_PACKET_HEADER = "<HHHBBQQ"   # schemaId version messageCount channel flags firstSeq sendTs
FMT_MESSAGE_HEADER = "<HHHH"     # blockLength templateId schemaId version
FMT_GROUP_HEADER = "<HH"         # blockLength numInGroup

FMT_ADD_ORDER = "<QqIHBB"        # orderId price quantity symbolId side reserved
FMT_MODIFY_ORDER = "<QqIHBB"     # orderId newPrice newQuantity symbolId side reason
FMT_DELETE_ORDER = "<QHBB"       # orderId symbolId side reserved
FMT_TRADE = "<QQQqIHBB"          # tradeId aggressorOrderId restingOrderId price qty symbolId side reserved
FMT_SNAPSHOT = "<QHBB"           # lastSequence symbolId flags reserved
FMT_SNAPSHOT_ORDER = "<QqIBBH"   # orderId price quantity side reserved reserved2
FMT_HEARTBEAT = "<Q"             # lastSequence
FMT_SEQUENCE_RESET = "<Q"        # newSequence

TEMPLATE = {
    "AddOrder": 1,
    "ModifyOrder": 2,
    "DeleteOrder": 3,
    "Trade": 4,
    "Snapshot": 5,
    "Heartbeat": 6,
    "SequenceReset": 7,
}

BLOCK_LENGTH = {
    "AddOrder": 24,
    "ModifyOrder": 24,
    "DeleteOrder": 12,
    "Trade": 40,
    "Snapshot": 12,
    "Heartbeat": 8,
    "SequenceReset": 8,
}

ORDER_BLOCK_LENGTH = 24

BID, ASK = 0, 1
REDUCE, REPLACE = 0, 1


def msg_header(name: str) -> bytes:
    return struct.pack(
        FMT_MESSAGE_HEADER, BLOCK_LENGTH[name], TEMPLATE[name], SCHEMA_ID, SCHEMA_VERSION
    )


