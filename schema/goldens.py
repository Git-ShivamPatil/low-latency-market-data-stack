#!/usr/bin/env python3
"""Build the golden byte vectors and the assertion code both test suites run.

    python3 schema/goldens.py            # write vectors and generated tests
    python3 schema/goldens.py --check    # fail if anything on disk is stale

Why this file does not import codegen.py
----------------------------------------
The whole point of a golden vector is to be an *independent* statement of what
the bytes are. If these files were produced by the Rust encoder, a wrong offset
in the generator would produce a wrong vector that the generated decoder would
then happily agree with, and the test would pass while the wire format was
broken. Cross-language wire drift fails exactly this way: silently, as a
corrupted field under load rather than as a compile error.

So the layout is written out here a third time, by hand, as explicit
`struct.pack` format strings taken from the table in docs/WIRE.md -- once in the
Rust emitter, once in the C++ emitter, once here. Three independent transcriptions
of the same table have to agree before a test can pass.

And to anchor those three against the specification itself, every message type
has one fully hand-typed hex literal below, checked against its packer at build
time. The values in those vectors were chosen to be readable in hex so a human
can verify the dump in schema/golden/*.txt against the spec table by eye.
Composite vectors (batches) are assembled from packers that have already been
anchored that way.
"""

