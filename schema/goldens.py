def emit_cpp(vs: list[Vector]) -> str:
    o: list[str] = []
    for line in BANNER:
        o.append(f"// {line}" if line else "//")
    o.append("")
    o.append("#pragma once")
    o.append("")
    o.append("#include <cstddef>")
    o.append("#include <cstdint>")
    o.append("#include <string>")
    o.append("")
    o.append('#include "wire/generated.hpp"')
    o.append('#include "golden_support.hpp"')
    o.append("")
    o.append("namespace mdstack::golden {")
    o.append("")
    o.append("using namespace mdstack::wire;")
    o.append("")
    for v in vs:
        emit_cpp_check(o, v)
        emit_cpp_build(o, v)
    o.append("struct Vector {")
    o.append("    const char* name;")
    o.append("    const char* file;")
    o.append("    const char* why;")
    o.append("    std::string (*check)(const std::byte*, std::size_t);")
    o.append("    std::size_t (*build)(std::byte*, std::size_t, std::string&);")
    o.append("};")
    o.append("")
    o.append("inline constexpr Vector kVectors[] = {")
    for v in vs:
        why = v.why.replace('"', '\\"')
        o.append(
            f'    {{"{v.name}", "{v.name}.bin", "{why}", check_{v.name}, build_{v.name}}},'
        )
    o.append("};")
    o.append("")
    o.append("}  // namespace mdstack::golden")
    return "\n".join(o).rstrip() + "\n"


def emit_cpp_check(o: list[str], v: Vector) -> None:
    o.append(f"// {v.why}")
    o.append(
        f"inline std::string check_{v.name}(const std::byte* buf, std::size_t len) {{"
    )
    o.append("    auto h = PacketHeaderDecoder::wrap(buf, len);")
    o.append('    if (!h) return "packet header: wrap failed";')
    o.append(f'    CHECK_EQ("packet.schemaId", h->schema_id(), {SCHEMA_ID});')
    o.append(f'    CHECK_EQ("packet.version", h->version(), {SCHEMA_VERSION});')
    o.append(
        f'    CHECK_EQ("packet.messageCount", h->message_count(), {len(v.messages)});'
    )
    o.append(f'    CHECK_EQ("packet.channel", h->channel(), {v.channel});')
    o.append(f'    CHECK_EQ("packet.flags", h->flags(), {v.flags});')
    o.append(
        f'    CHECK_EQ("packet.firstSequence", h->first_sequence(), '
        f"{v.first_sequence}ULL);"
    )
    o.append(
        f'    CHECK_EQ("packet.sendTimestampNs", h->send_timestamp_ns(), '
        f"{v.send_timestamp_ns}ULL);"
    )
    o.append(
        f'    CHECK_EQ("packet.isSnapshot", h->is_snapshot(), '
        f'{"true" if v.flags & 1 else "false"});'
    )
    o.append("    std::size_t pos = kPacketHeaderLen;")
    o.append(f"    const std::uint64_t first_seq = {v.first_sequence}ULL;")
    for i, m in enumerate(v.messages):
        o.append(f"    // message {i}")
        o.append("    {")
        o.append(
            f"        auto d = {m.kind}Decoder::wrap(buf + pos, len - pos);"
        )
        o.append(f'        if (!d) return "message {i}: not a decodable {m.kind}";')
        o.append(
            f'        CHECK_EQ("message {i} sequence", '
            f"static_cast<std::uint64_t>(first_seq + {i}ULL), "
            f"{(v.first_sequence + i) & 0xFFFFFFFFFFFFFFFF}ULL);"
        )
        for fname, fval in m.fields.items():
            emit_cpp_field_check(o, f"message {i}.{fname}", "d->", fname, fval)
        if m.kind == "Snapshot":
            o.append(
                f'        CHECK_EQ("message {i}.orders.numInGroup", d->orders_count(), {len(m.orders)});'
            )
            o.append(
                f'        CHECK_EQ("message {i}.orders.blockLength", d->orders_block_length(), {ORDER_BLOCK_LENGTH});'
            )
            for j, lvl in enumerate(m.orders):
                o.append(f"        {{")
                o.append(f"            auto l = d->order({j});")
                for fname, fval in lvl.items():
                    emit_cpp_field_check(
                        o, f"message {i}.orders[{j}].{fname}", "l.", fname, fval,
                        indent="            ",
                    )
                o.append("        }")
        o.append("        pos += d->total_len();")
        o.append("    }")
    o.append('    if (pos != len) return "trailing bytes past the last message";')
    o.append('    return "";')
    o.append("}")
    o.append("")


def emit_cpp_field_check(
    o: list[str], label: str, var: str, fname: str, fval: object,
    indent: str = "        ",
) -> None:
    if fname in ENUM_FIELDS:
        table = CPP_REASON if fname == "reason" else CPP_SIDE
        o.append(f"{indent}{{")
        o.append(f"{indent}    auto e = {var}{fname}();")
        o.append(f'{indent}    if (!e) return "{label}: undefined enum value";')
        o.append(
            f'{indent}    CHECK_EQ("{label}", static_cast<int>(*e), '
            f"static_cast<int>({table[fval]}));"
        )
        o.append(f"{indent}}}")
        return
    if isinstance(fval, int) and fval < 0:
        o.append(
            f'{indent}CHECK_EQ("{label}", {var}{fname}(), '
            f"static_cast<std::int64_t>({fval}));"
        )
        return
    suffix = "ULL" if isinstance(fval, int) and fval > 0xFFFFFFFF else ""
    o.append(f'{indent}CHECK_EQ("{label}", {var}{fname}(), {fval}{suffix});')


def emit_cpp_build(o: list[str], v: Vector) -> None:
    o.append(f"// Re-encodes `{v.name}` from the same values check_{v.name} asserts.")
    o.append(
        f"inline std::size_t build_{v.name}(std::byte* out, std::size_t cap, "
        "std::string& err) {"
    )
    o.append("    auto ph = encode_packet_header(out, cap")
    o.append(f"        , static_cast<std::uint8_t>({v.channel})")
    o.append(f"        , static_cast<std::uint8_t>({v.flags})")
    o.append(f"        , {v.first_sequence}ULL")
    o.append(f"        , {v.send_timestamp_ns}ULL")
    o.append("    );")
    o.append('    if (!ph) { err = "packet header did not fit"; return 0; }')
    o.append("    std::size_t pos = *ph;")
    for idx, m in enumerate(v.messages):
        o.append(f"    // message {idx}")
        if m.kind == "Snapshot":
            f = m.fields
            o.append("    {")
            o.append(
                f"        auto e = {m.kind}Encoder::start(out + pos, cap - pos"
            )
            o.append(f"            , {f['last_sequence']}ULL")
            o.append(f"            , static_cast<std::uint16_t>({f['symbol_id']})")
            o.append(f"            , static_cast<std::uint8_t>({f['flags']})")
            o.append("        );")
            o.append(f'        if (!e) {{ err = "message {idx} did not fit"; return 0; }}')
            for j, lv in enumerate(m.orders):
                o.append("        if (!e->push_order(")
                o.append(f"                static_cast<std::uint64_t>({lv['order_id']}ULL)")
                o.append(f"                , static_cast<std::int64_t>({lv['price']})")
                o.append(f"                , static_cast<std::uint32_t>({lv['quantity']})")
                o.append(f"                , {CPP_SIDE[lv['side']]}")
                o.append(
                    f'        )) {{ err = "message {idx} order {j} did not fit"; return 0; }}'
                )
            o.append("        pos += e->finish();")
            o.append("    }")
            continue
        fn = {
            "AddOrder": "encode_add_order", "ModifyOrder": "encode_modify_order",
            "DeleteOrder": "encode_delete_order", "Trade": "encode_trade",
            "Heartbeat": "encode_heartbeat", "SequenceReset": "encode_sequence_reset",
        }[m.kind]
        o.append("    {")
        o.append(f"        auto n = {fn}(out + pos, cap - pos")
        for fname, fval in m.fields.items():
            if fname in ENUM_FIELDS:
                table = CPP_REASON if fname == "reason" else CPP_SIDE
                o.append(f"            , {table[fval]}")
            else:
                o.append(f"            , {cpp_arg(m.kind, fname, fval)}")
        o.append("        );")
        o.append(f'        if (!n) {{ err = "message {idx} did not fit"; return 0; }}')
        o.append("        pos += *n;")
        o.append("    }")
    o.append(
        f"    if (!patch_message_count(out, cap, "
        f"static_cast<std::uint16_t>({len(v.messages)})))"
    )
    o.append('        { err = "could not patch messageCount"; return 0; }')
    o.append("    return pos;")
    o.append("}")
    o.append("")


CPP_CAST = {8: "std::uint64_t", 4: "std::uint32_t", 2: "std::uint16_t", 1: "std::uint8_t"}


def cpp_arg(kind: str, fname: str, fval: object) -> str:
    if fname in ("price", "new_price"):
        return f"static_cast<std::int64_t>({fval})"
    w = FIELD_WIDTH[kind][fname]
    assert isinstance(fval, int) and fval >= 0, f"{kind}.{fname} is unsigned on the wire"
    return f"static_cast<{CPP_CAST[w]}>({fval}ULL)"


