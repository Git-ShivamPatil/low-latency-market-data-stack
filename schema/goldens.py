def emit_rust(vs: list[Vector]) -> str:
    o: list[str] = []
    for line in BANNER:
        o.append(f"//! {line}" if line else "//!")
    o.append("")
    o.append("#![allow(clippy::unreadable_literal)]")
    o.append("")
    o.append("use wire::*;")
    o.append("")
    o.append("// Comparison helpers. Each names the field, because a golden-vector")
    o.append("// failure that says only \"mismatch\" costs more time than the test saved.")
    o.append("macro_rules! eq_fn {")
    o.append("    ($name:ident, $ty:ty) => {")
    o.append("        #[allow(dead_code)]")
    o.append("        fn $name(label: &str, actual: $ty, expected: $ty) -> Result<(), String> {")
    o.append("            if actual != expected {")
    o.append("                return Err(format!(\"{label}: expected {expected}, got {actual}\"));")
    o.append("            }")
    o.append("            Ok(())")
    o.append("        }")
    o.append("    };")
    o.append("}")
    o.append("")
    o.append("eq_fn!(eq_u8, u8);")
    o.append("eq_fn!(eq_u16, u16);")
    o.append("eq_fn!(eq_u32, u32);")
    o.append("eq_fn!(eq_u64, u64);")
    o.append("eq_fn!(eq_i64, i64);")
    o.append("eq_fn!(eq_bool, bool);")
    o.append("")
    o.append("/// One golden vector: the file, the field values, and the encoder path")
    o.append("/// that must reproduce the file byte for byte.")
    o.append("pub struct Vector {")
    o.append("    pub name: &'static str,")
    o.append("    pub file: &'static str,")
    o.append("    pub why: &'static str,")
    o.append("    pub check: fn(&[u8]) -> Result<(), String>,")
    o.append("    pub build: fn(&mut [u8]) -> Result<usize, WireError>,")
    o.append("}")
    o.append("")
    o.append("pub const VECTORS: &[Vector] = &[")
    for v in vs:
        o.append("    Vector {")
        o.append(f'        name: "{v.name}",')
        o.append(f'        file: "{v.name}.bin",')
        o.append(f'        why: "{v.why}",')
        o.append(f"        check: check_{v.name},")
        o.append(f"        build: build_{v.name},")
        o.append("    },")
    o.append("];")
    o.append("")
    for v in vs:
        emit_rust_check(o, v)
        emit_rust_build(o, v)
    return "\n".join(o).rstrip() + "\n"


def emit_rust_check(o: list[str], v: Vector) -> None:
    o.append(f"/// {v.why}")
    o.append(f"pub fn check_{v.name}(buf: &[u8]) -> Result<(), String> {{")
    o.append("    let r = PacketReader::new(buf).map_err(|e| format!(\"packet header: {e}\"))?;")
    o.append("    let h = r.header();")
    o.append(f"    eq_u16(\"packet.schemaId\", h.schema_id(), {SCHEMA_ID})?;")
    o.append(f"    eq_u16(\"packet.version\", h.version(), {SCHEMA_VERSION})?;")
    o.append(
        f'    eq_u16("packet.messageCount", h.message_count(), {len(v.messages)})?;'
    )
    o.append(f'    eq_u8("packet.channel", h.channel(), {v.channel})?;')
    o.append(f'    eq_u8("packet.flags", h.flags(), {v.flags})?;')
    o.append(
        f'    eq_u64("packet.firstSequence", h.first_sequence(), {v.first_sequence})?;'
    )
    o.append(
        f'    eq_u64("packet.sendTimestampNs", h.send_timestamp_ns(), '
        f"{v.send_timestamp_ns})?;"
    )
    snap = "true" if v.flags & 1 else "false"
    o.append(f'    eq_bool("packet.isSnapshot", h.is_snapshot(), {snap})?;')
    o.append("")
    o.append("    let mut it = r.messages();")
    for i, m in enumerate(v.messages):
        seq = (v.first_sequence + i) & 0xFFFFFFFFFFFFFFFF
        o.append(f"    // message {i}")
        o.append("    let (seq, msg) = it")
        o.append("        .next()")
        o.append(f'        .ok_or_else(|| "message {i}: missing".to_string())?')
        o.append(f'        .map_err(|e| format!("message {i}: {{e}}"))?;')
        o.append(f'    eq_u64("message {i} sequence", seq, {seq})?;')
        o.append(f"    let Message::{m.kind}(d) = msg else {{")
        o.append(
            f'        return Err(format!("message {i}: expected {m.kind}, got template {{}}", msg.template_id()));'
        )
        o.append("    };")
        for fname, fval in m.fields.items():
            emit_rust_field_check(o, f"message {i}.{fname}", "d", fname, fval, m.kind)
        if m.kind == "Snapshot":
            o.append(
                f'    eq_u16("message {i}.orders.numInGroup", d.orders_count(), {len(m.orders)})?;'
            )
            o.append(
                f'    eq_u16("message {i}.orders.blockLength", d.orders_block_length(), {ORDER_BLOCK_LENGTH})?;'
            )
            o.append("    let mut lv = d.orders();")
            for j, lvl in enumerate(m.orders):
                o.append(
                    f'    let l = lv.next().ok_or_else(|| "message {i}: level {j} missing".to_string())?;'
                )
                for fname, fval in lvl.items():
                    emit_rust_field_check(
                        o, f"message {i}.orders[{j}].{fname}", "l", fname, fval, "level"
                    )
            o.append(
                f'    if lv.next().is_some() {{ return Err("message {i}: extra levels".to_string()); }}'
            )
        o.append("")
    o.append('    if it.next().is_some() {')
    o.append('        return Err("extra messages past messageCount".to_string());')
    o.append("    }")
    o.append("    Ok(())")
    o.append("}")
    o.append("")


def emit_rust_field_check(
    o: list[str], label: str, var: str, fname: str, fval: object, kind: str
) -> None:
    if fname in ENUM_FIELDS:
        table = RUST_REASON if fname == "reason" else RUST_SIDE
        ty = "ModifyReason" if fname == "reason" else "Side"
        o.append(
            f'    if {var}.{fname}().map_err(|e| format!("{label}: {{e}}"))? != {table[fval]} {{'
        )
        o.append(
            f'        return Err(format!("{label}: expected {table[fval]}, got {{:?}}", {var}.{fname}()));'
        )
        o.append("    }")
        return
    width = {
        8: "eq_u64", 4: "eq_u32", 2: "eq_u16", 1: "eq_u8",
    }
    if kind == "level":
        w = ORDER_FIELD_WIDTH[fname]
    else:
        w = FIELD_WIDTH[kind][fname]
    if fname in ("price", "new_price"):
        o.append(f'    eq_i64("{label}", {var}.{fname}(), {fval})?;')
        return
    o.append(f'    {width[w]}("{label}", {var}.{fname}(), {rust_lit(fname, fval)})?;')


def emit_rust_build(o: list[str], v: Vector) -> None:
    o.append(f"/// Re-encodes `{v.name}` from the same values `check_{v.name}` asserts.")
    o.append(f"pub fn build_{v.name}(out: &mut [u8]) -> Result<usize, WireError> {{")
    o.append("    let mut w = PacketWriter::new(")
    o.append("        out,")
    o.append(f"        {v.channel},")
    o.append(f"        {v.flags},")
    o.append(f"        {v.first_sequence},")
    o.append(f"        {v.send_timestamp_ns},")
    o.append("    )?;")
    for m in v.messages:
        if m.kind == "Snapshot":
            f = m.fields
            o.append("    let n = {")
            # A group with no entries never mutates the encoder, and clippy
            # rejects an unnecessary `mut` under -D warnings.
            binding = "let mut e" if m.orders else "let e"
            o.append(f"        {binding} = SnapshotEncoder::start(")
            o.append("            w.tail(),")
            o.append(f"            {f['last_sequence']},")
            o.append(f"            {f['symbol_id']},")
            o.append(f"            {f['flags']},")
            o.append("        )?;")
            for lv in m.orders:
                o.append("        e.push_order(")
                o.append(f"            {lv['order_id']},")
                o.append(f"            {lv['price']},")
                o.append(f"            {lv['quantity']},")
                o.append(f"            {RUST_SIDE[lv['side']]},")
                o.append("        )?;")
            o.append("        e.finish()")
            o.append("    };")
            o.append("    w.commit(n)?;")
            continue
        args = []
        for fname, fval in m.fields.items():
            if fname in ENUM_FIELDS:
                table = RUST_REASON if fname == "reason" else RUST_SIDE
                args.append(table[fval])
            else:
                args.append(str(fval))
        method = {
            "AddOrder": "add_order", "ModifyOrder": "modify_order",
            "DeleteOrder": "delete_order", "Trade": "trade",
            "Heartbeat": "heartbeat", "SequenceReset": "sequence_reset",
        }[m.kind]
        o.append(f"    w.{method}({', '.join(args)})?;")
    o.append("    Ok(w.finish())")
    o.append("}")
    o.append("")


