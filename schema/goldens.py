def rustfmt(path: Path) -> None:
    """Format generated Rust in place.

    Duplicated from codegen.py rather than imported: this file deliberately does
    not depend on the emitters, and one four-line helper is a cheaper price than
    a caveat on that independence.
    """
    exe = shutil.which("rustfmt")
    if exe is None:
        print("  note: rustfmt not found; generated Rust left unformatted", file=sys.stderr)
        return
    subprocess.run([exe, "--edition", "2021", str(path)], check=True)


def format_rust_text(text: str, near: Path) -> str:
    """Return `text` as rustfmt would write it, without touching `near`."""
    scratch = near.parent / ".goldens.fmt.rs"
    scratch.parent.mkdir(parents=True, exist_ok=True)
    scratch.write_text(text, encoding="utf-8", newline="\n")
    try:
        rustfmt(scratch)
        return scratch.read_text(encoding="utf-8")
    finally:
        scratch.unlink(missing_ok=True)


def write(path: Path, data: bytes | str, check: bool, results: list[bool]) -> None:
    if isinstance(data, str):
        blob = data.encode("utf-8")
    else:
        blob = data
    current = path.read_bytes() if path.exists() else None
    rel = path.relative_to(REPO)
    if check:
        if current == blob:
            print(f"  ok    {rel}")
            results.append(True)
        else:
            print(f"  STALE {rel}", file=sys.stderr)
            results.append(False)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(blob)
    print(f"  wrote {rel}")
    results.append(True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="do not write; exit non-zero if stale")
    args = ap.parse_args()

    vs = vectors()

    # The hand-typed anchors come first: if a packer disagrees with the byte
    # table, nothing below is worth writing.
    by_name = {v.name: v for v in vs}
    for name, hexstr in HAND_TYPED.items():
        v = by_name.get(name)
        if v is None:
            raise SystemExit(f"HAND_TYPED names {name!r}, which is not a vector")
        expected = hexbytes(hexstr)
        actual = v.pack()
        if expected != actual:
            print(f"hand-typed anchor {name} does not match the packer:", file=sys.stderr)
            print(f"  hand-typed: {expected.hex(' ')}", file=sys.stderr)
            print(f"  packed:     {actual.hex(' ')}", file=sys.stderr)
            return 1
    covered = {m.kind for name in HAND_TYPED for m in by_name[name].messages}
    missing = set(TEMPLATE) - covered
    if missing:
        print(
            f"no hand-typed anchor covers: {', '.join(sorted(missing))}", file=sys.stderr
        )
        return 1
    print(f"{len(HAND_TYPED)} hand-typed anchors agree with the packers")

    results: list[bool] = []
    for v in vs:
        write(GOLDEN_DIR / f"{v.name}.bin", v.pack(), args.check, results)
        write(GOLDEN_DIR / f"{v.name}.txt", annotate(v), args.check, results)
    # rustfmt is part of the committed output, so --check has to compare against
    # formatted text or it would report a false staleness every run.
    write(RUST_OUT, format_rust_text(emit_rust(vs), RUST_OUT), args.check, results)
    write(CPP_OUT, emit_cpp(vs), args.check, results)

    if not all(results):
        print(
            "\ngolden vectors are stale: run `make goldens` and commit the result",
            file=sys.stderr,
        )
        return 1
    print(f"{len(vs)} vectors")
    return 0


if __name__ == "__main__":
    sys.exit(main())
