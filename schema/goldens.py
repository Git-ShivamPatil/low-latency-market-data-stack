def annotate(v: Vector) -> str:
    out: list[str] = []
    out.append(f"{v.name}.bin")
    out.append("=" * (len(v.name) + 4))
    out.append("")
    out.append(v.why)
    out.append("")
    out.append("Generated by schema/goldens.py. This dump exists so the vector can be")
    out.append("checked against the byte table in docs/WIRE.md by eye rather than by")
    out.append("running the code that is supposed to be under test.")
    out.append("")

    data = v.pack()
    pos = 0

    def row(n: int, label: str) -> None:
        nonlocal pos
        chunk = data[pos : pos + n]
        out.append(f"  {pos:04x}  {chunk.hex(' '):<48}  {label}")
        pos += n

    out.append("packetHeader")
    row(2, f"schemaId = {SCHEMA_ID}")
    row(2, f"version = {SCHEMA_VERSION}")
    row(2, f"messageCount = {len(v.messages)}")
    row(1, f"channel = {v.channel}")
    row(1, f"flags = 0x{v.flags:02x}")
    row(8, f"firstSequence = {v.first_sequence} (0x{v.first_sequence:016x})")
    row(8, f"sendTimestampNs = {v.send_timestamp_ns} (0x{v.send_timestamp_ns:016x})")

    for i, m in enumerate(v.messages):
        out.append("")
        out.append(f"message {i}  sequence = {v.first_sequence + i}  {m.kind}")
        row(2, f"blockLength = {BLOCK_LENGTH[m.kind]}")
        row(2, f"templateId = {TEMPLATE[m.kind]}")
        row(2, f"schemaId = {SCHEMA_ID}")
        row(2, f"version = {SCHEMA_VERSION}")
        for fname, fval in m.fields.items():
            width = FIELD_WIDTH[m.kind][fname]
            row(width, f"{fname} = {fval}{signed_note(fval)}")
        if m.kind == "Snapshot":
            row(1, "reserved = 0")
            row(2, f"orders.blockLength = {ORDER_BLOCK_LENGTH}")
            row(2, f"orders.numInGroup = {len(m.orders)}")
            for j, lv in enumerate(m.orders):
                for fname, fval in lv.items():
                    width = ORDER_FIELD_WIDTH[fname]
                    row(width, f"orders[{j}].{fname} = {fval}")
                row(1, f"orders[{j}].reserved = 0")
                row(2, f"orders[{j}].reserved2 = 0")
        elif m.kind in ("AddOrder", "DeleteOrder", "Trade"):
            row(1, "reserved = 0")

    if pos != len(data):
        raise AssertionError(
            f"{v.name}: annotated {pos} bytes but the vector is {len(data)}. "
            "The dump and the packer disagree about the layout."
        )
    out.append("")
    out.append(f"total {len(data)} bytes")
    out.append("")
    return "\n".join(out)


def signed_note(v: object) -> str:
    return " (negative)" if isinstance(v, int) and v < 0 else ""


